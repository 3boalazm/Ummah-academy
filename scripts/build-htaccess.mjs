// Generates dist/.htaccess (Apache / LiteSpeed — Hostinger) from vercel.json, so the
// 301s and security headers stay defined in ONE place. Run after `astro build`:
//   npm run build:hostinger
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const dist = join(root, 'dist');
if (!existsSync(dist)) throw new Error('dist/ missing — run `npm run build` first');

const cfg = JSON.parse(readFileSync(join(root, 'vercel.json'), 'utf8'));

/** Vercel source pattern → mod_rewrite regex (no leading slash). */
function toRegex(source) {
  let s = source.replace(/^\//, '');
  const wild = s.endsWith('/:path*');
  if (wild) s = s.slice(0, -'/:path*'.length);
  s = s.replace(/\{\/\}\?$/, '').replace(/\/$/, '');
  const esc = s.replace(/[.+?^$()|[\]\\]/g, '\\$&');
  return wild ? `^${esc}(/.*)?$` : `^${esc}/?$`;
}

const redirects = cfg.redirects.map(
  (r) => `RewriteRule ${toRegex(r.source)} ${r.destination} [R=301,L]`,
);

const global = cfg.headers.find((h) => h.source === '/(.*)' && !h.has);
const globalHeaders = global.headers
  .map((h) => `  Header always set ${h.key} "${h.value.replace(/"/g, '\\"')}"`)
  .join('\n');

const out = `# Generated by scripts/build-htaccess.mjs from vercel.json — do not edit by hand.
Options -Indexes -MultiViews
DirectoryIndex index.html
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
RewriteEngine On

# HTTPS + apex canonical (guards keep it loop-safe behind a CDN/proxy)
RewriteCond %{HTTPS} off
RewriteCond %{HTTP:X-Forwarded-Proto} !https
RewriteRule ^ https://ummahacademy.net%{REQUEST_URI} [R=301,L]
RewriteCond %{HTTP_HOST} ^www\\. [NC]
RewriteRule ^ https://ummahacademy.net%{REQUEST_URI} [R=301,L]

# Legacy WordPress sitemaps → new sitemap (keeps Search Console submissions working)
RewriteRule ^(sitemap|sitemap_index|wp-sitemap|post-sitemap|page-sitemap)\\.xml$ /sitemap-index.xml [R=301,L]

# Legacy URLs (from vercel.json)
${redirects.join('\n')}
</IfModule>

<IfModule mod_headers.c>
${globalHeaders}
  <FilesMatch "^(sw\\.js)$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
    Header set Service-Worker-Allowed "/"
  </FilesMatch>
  <FilesMatch "^manifest\\.webmanifest$">
    Header set Cache-Control "public, max-age=3600"
  </FilesMatch>
</IfModule>

<IfModule mod_mime.c>
  AddType application/manifest+json .webmanifest
  AddType image/avif .avif
  AddType image/webp .webp
  AddType font/woff2 .woff2
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css application/javascript text/javascript application/json application/xml text/xml image/svg+xml application/manifest+json
</IfModule>
`;
writeFileSync(join(dist, '.htaccess'), out);

// Per-directory cache rules (more robust than env-flag tricks across Apache/LiteSpeed)
const dirRules = {
  _astro: 'public, max-age=31536000, immutable',
  downloads: 'public, max-age=86400, stale-while-revalidate=604800',
};
for (const [dir, value] of Object.entries(dirRules)) {
  const p = join(dist, dir);
  if (!existsSync(p)) continue;
  writeFileSync(join(p, '.htaccess'), `<IfModule mod_headers.c>\n  Header set Cache-Control "${value}"\n</IfModule>\n`);
}
const adminDir = join(dist, 'admin');
if (existsSync(adminDir)) {
  writeFileSync(
    join(adminDir, '.htaccess'),
    `<IfModule mod_headers.c>\n  Header set X-Robots-Tag "noindex, nofollow"\n  Header set Cache-Control "no-cache"\n</IfModule>\n`,
  );
}
console.log(`.htaccess written: ${cfg.redirects.length} redirects + headers + cache rules`);
